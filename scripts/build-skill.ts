// The practitioner reference skill (task PM-65; docs/post-mvp/design/practitioner-reference.md): builds the Agent Skill `tcm-practitioner-reference` into
// dist/skills/tcm-practitioner-reference/ and packs it as dist/skills/tcm-practitioner-reference.skill, to install in Claude.
//   node scripts/build-skill.ts            (pnpm skill:build)
//   env: APP_OVERRIDES, APP_DOSE_DISPLAY — the build's restrictions, applied as the bundle applies them (scripts/bundle-data.ts); APP_BUILD_ID names the build
// The skill is: its instructions and references, written in skills/tcm-practitioner-reference/; one script — the app's own practitioner pipeline (apps/web/src/practitioner:
// the engine, the summary, the medication plan) bundled for Node with the bundler Vite brings, so nothing is downloaded; the knowledge base it reads — the closed beta's
// (the release profile with its draft label) with its study reference, read in the practitioner's role; the vocabulary, generated by that script from that knowledge base; and
// the licence and the notice of the data it carries. A build whose restrictions serve no study reference has no practitioner role, and the build refuses.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildChunks } from "../packages/kb/src/bundle.ts";
import { readDataFiles } from "../packages/kb/node/fromDisk.ts";
import { overridesOf } from "./bundle-data.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SKILL = "tcm-practitioner-reference";
export const SOURCE = join(root, "skills", SKILL);
export const OUT = join(root, "dist", "skills");
const ENTRY = join(root, "apps", "web", "src", "practitioner", "node", "cli.ts");
const sha = (text: string): string => createHash("sha256").update(text).digest("hex");

/** The build's name: APP_BUILD_ID, else the commit (with "+" when the tree has changes), else "local". */
export function buildId(): string {
  if (process.env.APP_BUILD_ID) return process.env.APP_BUILD_ID;
  try {
    const head = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
    const dirty = execFileSync("git", ["status", "--porcelain"], { cwd: root, encoding: "utf8" }).trim() !== "";
    return `${head}${dirty ? "+" : ""}`;
  } catch {
    return "local";
  }
}

/** The knowledge base the skill carries (apps/web/src/practitioner/kbFile.ts reads it): the closed beta's chunks and its study reference, named by a hash of both. */
export function kbFile(build: string, overrides?: unknown): { readonly file: Record<string, unknown>; readonly patterns: number; readonly formulas: number } {
  const built = buildChunks(readDataFiles(), { profile: "release", version: "pending", draftLabel: true, overrides });
  if (built.referenceFile === null) throw new Error("the build serves no study reference (dose_display is off, or an override takes it away): there is no practitioner role, so no practitioner reference");
  const { schemaVersion, core, formulas, herbs, citations, guidance } = built.chunks;
  const body = { schemaVersion, core, formulas, herbs, citations, guidance };
  const version = `skill-${sha(JSON.stringify([body, built.referenceFile])).slice(0, 12)}`;
  return {
    file: { format: "tcm-practitioner-kb", version: 1, build, chunks: { version, ...body }, reference: built.referenceFile },
    patterns: core.patterns.items.length, formulas: built.referenceFile.formulas.items.length,
  };
}

interface Rolldown { rolldown(o: unknown): Promise<{ write(o: unknown): Promise<unknown>; close(): Promise<void> }> }

/** The script: the app's practitioner pipeline for Node, in one file, with the bundler of the app's Vite (resolved through it: no other dependency). */
export async function bundleScript(file: string, build: string): Promise<void> {
  const viaWeb = createRequire(join(root, "apps", "web", "package.json"));
  const { rolldown } = (await import(pathToFileURL(createRequire(viaWeb.resolve("vite")).resolve("rolldown")).href)) as Rolldown;
  const bundle = await rolldown({
    input: ENTRY, platform: "node", logLevel: "warn", external: [/^node:/],
    transform: { target: "node18", define: { __APP_PROFILE__: JSON.stringify("release"), __APP_BUILD__: JSON.stringify(build) } },
  });
  try {
    await bundle.write({ file, format: "esm", banner: `// ${SKILL} ${build} — the practitioner reference of TCM Self-Check, generated by scripts/build-skill.ts; Apache-2.0, see LICENSE and NOTICE.` });
  } finally {
    await bundle.close();
  }
}

/** A .skill file: a zip of the skill's folder (its name at the root), without a root `evals` folder — the format of Claude's skill packager. */
function pack(dir: string, file: string): void {
  const py = [
    "import sys, zipfile, pathlib",
    "src, out = pathlib.Path(sys.argv[1]), sys.argv[2]",
    "with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:",
    "    for p in sorted(src.rglob('*')):",
    "        rel = p.relative_to(src.parent)",
    "        if p.is_file() and p.name != '.DS_Store' and not (len(rel.parts) > 1 and rel.parts[1] == 'evals'):",
    "            z.write(p, rel.as_posix())",
  ].join("\n");
  execFileSync("python3", ["-c", py, dir, file]);
}

export interface SkillBuild { readonly dir: string; readonly skill: string; readonly build: string; readonly kb: string; readonly bytes: { readonly script: number; readonly kb: number; readonly skill: number } }

/** Build the skill into `out` (dist/skills): the folder and the .skill file. */
export async function buildSkill(opts: { out?: string; build?: string; overrides?: unknown } = {}): Promise<SkillBuild> {
  const out = opts.out ?? OUT;
  const build = opts.build ?? buildId();
  const dir = join(out, SKILL);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(join(dir, "scripts"), { recursive: true });
  // the knowledge base, the script, the instructions and references written for the skill (the counts filled in), the licence and the notice
  const { file, patterns, formulas } = kbFile(build, opts.overrides);
  writeFileSync(join(dir, "scripts", "kb.json"), JSON.stringify(file));
  await bundleScript(join(dir, "scripts", "reference.mjs"), build);
  cpSync(join(SOURCE, "references"), join(dir, "references"), { recursive: true });
  cpSync(join(SOURCE, "assets"), join(dir, "assets"), { recursive: true });
  writeFileSync(join(dir, "SKILL.md"), readFileSync(join(SOURCE, "SKILL.md"), "utf8").replaceAll("{{PATTERNS}}", String(patterns)).replaceAll("{{FORMULAS}}", String(formulas)));
  for (const f of ["LICENSE", "NOTICE"]) cpSync(join(root, f), join(dir, f));
  // the vocabulary, made by the script itself from the knowledge base it reads; then the example case, run as the skill runs it
  const script = join(dir, "scripts", "reference.mjs");
  writeFileSync(join(dir, "references", "vocabulary.md"), execFileSync(process.execPath, [script, "--vocabulary"], { encoding: "utf8" }));
  const version = JSON.parse(execFileSync(process.execPath, [script, "--version"], { encoding: "utf8" })) as { kb: string; role: string };
  if (version.role !== "practitioner") throw new Error(`the script reads the knowledge base as ${version.role}, not as a practitioner`);
  const report = execFileSync(process.execPath, [script, join(dir, "assets", "example-case.json")], { encoding: "utf8" });
  if (!report.startsWith("# ")) throw new Error(`the example case gave no report:\n${report.slice(0, 400)}`);
  const skill = join(out, `${SKILL}.skill`);
  rmSync(skill, { force: true });
  pack(dir, skill);
  return { dir, skill, build, kb: version.kb, bytes: { script: statSync(script).size, kb: statSync(join(dir, "scripts", "kb.json")).size, skill: statSync(skill).size } };
}

if (import.meta.main) {
  if (!existsSync(join(SOURCE, "SKILL.md"))) throw new Error(`no skill at ${SOURCE}`);
  const r = await buildSkill({ overrides: overridesOf(process.env.APP_OVERRIDES, process.env.APP_DOSE_DISPLAY) });
  const kb = (n: number): string => `${(n / 1024).toFixed(0)} KB`;
  console.log(`skill: ${SKILL} ${r.build}, knowledge base ${r.kb} — script ${kb(r.bytes.script)}, knowledge base ${kb(r.bytes.kb)}, packed ${kb(r.bytes.skill)} → ${r.skill}`);
}
