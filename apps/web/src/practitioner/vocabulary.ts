// The practitioner reference (PM-65): the vocabulary a case may use — every id of the knowledge base the skill maps a practitioner's words onto, with its Chinese and
// English names — as one Markdown file the skill reads (`references/vocabulary.md`). Generated from the knowledge base and the app's words at the skill's build, so it
// can never name an id the engine does not know.
import { createI18n } from "@tcm/i18n";
import type { KnowledgeBase } from "@tcm/kb";
import { catalogs, type MessageKey } from "../i18n/catalogs.ts";
import { RATE_GROUP } from "../screens/observe/model.ts";
import { MED_CLASSES, SERIOUS_CONDITIONS } from "../screens/profile/model.ts";

const cell = (s: string): string => s.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const row = (cells: readonly string[]): string => `| ${cells.map(cell).join(" | ")} |`;
const table = (head: readonly string[], rows: readonly (readonly string[])[]): string[] => [row(head), `|${head.map(() => "---").join("|")}|`, ...rows.map(row)];

/** The vocabulary of the knowledge base as Markdown. */
export function vocabularyOf(kb: KnowledgeBase): string {
  const zh = createI18n<MessageKey>(catalogs, "zh-Hant"), en = createI18n<MessageKey>(catalogs, "en");
  const both = (key: string): [string, string] => [zh.t(key as MessageKey), en.t(key as MessageKey)];
  const sym = (id: string): [string, string] => { const s = kb.symptoms.get(id); return s ? [s["zh-Hant"], s.en] : [id, id]; };
  const out: string[] = [
    "# Vocabulary of the knowledge base",
    "",
    "Every id a case may use, with its Chinese and English names. Map what the practitioner says onto these ids; what has no item here goes under `unmapped` (it is shown in the report and never used).",
    "",
    `Knowledge base ${kb.version} · ${kb.symptoms.size} findings in ${kb.questions.length} questions · ${kb.tongue.features.length} tongue features · ${kb.pulse.pulses.length} pulses · generated by the skill's build: do not edit.`,
    "",
    "## Contents",
    "",
    "1. [Person](#1-person): medicine classes, serious long-term conditions",
    "2. [Red flags](#2-red-flags)",
    "3. [Constitutions](#3-constitutions)",
    "4. [Course](#4-course)",
    "5. [Findings of the inquiry, by question](#5-findings-of-the-inquiry-by-question)",
    "6. [Tongue](#6-tongue)",
    "7. [Pulse](#7-pulse)",
    "",
    "## 1. Person",
    "",
    "### Medicine classes — `person.medications.classes`",
    "",
    "A named medicine of no listed class counts as `other` (give its name under `person.medications.named`).",
    "",
    ...table(["id", "中文", "English"], MED_CLASSES.map((c) => [`\`${c}\``, ...both(`intake.profile.meds.${c}`)])),
    "",
    "### Serious long-term conditions — `person.conditions.items`",
    "",
    ...table(["id", "中文", "English"], SERIOUS_CONDITIONS.map((id) => { const f = kb.redFlags.find((x) => x.id === id)!; return [`\`${id}\``, f.text["zh-Hant"], f.text.en]; })),
    "",
    "## 2. Red flags",
    "",
    "`redFlags`: the level-A and level-B items the practitioner found. Level A asks for emergency care; level B for a physician soon. Either way the reference lists no herbs.",
    "",
    ...table(["id", "level", "中文", "English"], kb.redFlags.filter((f) => f.level !== "C").map((f) => [`\`${f.id}\``, f.level, f.text["zh-Hant"], f.text.en])),
    "",
    "## 3. Constitutions",
    "",
    "The case's `constitution` is `{ \"primary\": id }`, with `\"secondary\": id` for a second biased type (兼夾).",
    "",
    ...table(["id", "中文", "English"], kb.constitutions.map((c) => [`\`${c.id}\``, c.name["zh-Hant"], c.name.en ?? ""])),
    "",
    "## 4. Course",
    "",
    "`course`: how long the present complaint has lasted.",
    "",
    ...table(["value", "中文", "English"], kb.questionById.get("Q_COURSE")!.options.filter((o) => o.context).map((o) => [`\`${o.context!.course}\``, o.label["zh-Hant"], o.label.en])),
    "",
    "## 5. Findings of the inquiry, by question",
    "",
    "`findings`: a finding by id → `present` (or its severity `light` | `moderate` | `severe` where the question grades it), `absent` (the practitioner denies it) or `unsure`. A finding not mentioned stays unknown.",
    "`answers`: a question answered as a whole → its option ids, `\"none\"` or `\"skip\"`; its other options are then recorded absent. Give a question one way or the other, not both.",
    "",
  ];
  const dims = [...new Set(kb.questions.map((q) => q.dimension))];
  for (const dim of dims) {
    const [dzh, den] = both(`intake.inquiry.dimension.${dim}`);
    out.push(`### ${dzh} · ${den}`, "");
    for (const q of kb.questions.filter((x) => x.dimension === dim).sort((a, b) => a.order - b.order)) {
      const notes = [
        q.core ? "core" : "follow-up",
        q.select === "one" ? "one option" : "any options",
        ...(q.requires?.sex ? [`${q.requires.sex} only`] : []),
        ...(q.follows ? [`asked when one of ${q.follows.map((s) => `\`${s}\``).join(", ")} is present`] : []),
        ...(q.exclusive_groups.length > 0 ? [`exclusive: ${q.exclusive_groups.map((g) => g.map((s) => `\`${s}\``).join(" ⟂ ")).join("; ")}`] : []),
      ];
      out.push(`**\`${q.id}\`** — ${q.prompt["zh-Hant"]} / ${q.prompt.en} *(${notes.join(" · ")})*`, "");
      const rows = q.options.filter((o) => !o.context).flatMap((o) => (o.none ? [[`\`${o.id}\``, "—", o.label["zh-Hant"], o.label.en, ""]] : o.symptoms.map((s, i) => [i === 0 ? `\`${o.id}\`` : "", `\`${s}\``, ...sym(s), q.graded.includes(s) ? "✓" : ""])));
      out.push(...table(["option", "finding", "中文", "English", "graded"], rows), "");
    }
  }
  out.push("## 6. Tongue", "", "`tongue.body`, `tongue.shape`, `tongue.coat`: the chosen features of the category (the others are recorded absent), or `\"normal\"`. `tongue.signs`: zone features and special signs present.", "");
  const groups: [string, string][] = [["body", "tongue.body"], ["shape", "tongue.shape"], ["coat", "tongue.coat"]];
  for (const [category, field] of groups) out.push(`### \`${field}\``, "", ...table(["id", "中文", "English", "意義"], kb.tongue.features.filter((f) => f.category === category).map((f) => [`\`${f.id}\``, f.name["zh-Hant"], f.name.en, f.meaning ?? ""])), "");
  out.push("### `tongue.signs`", "", ...table(["id", "where", "中文", "English", "意義"], kb.tongue.features.filter((f) => !groups.some(([c]) => c === f.category)).map((f) => [`\`${f.id}\``, `${f.category} · ${f.zone}`, f.name["zh-Hant"], f.name.en, f.meaning ?? ""])), "");
  out.push("## 7. Pulse", "", `\`pulse.qualities\`: the pulses felt. \`pulse.rate\` (beats per minute) gives the rate pulses itself — give the rate or a rate pulse (group \`${RATE_GROUP}\`), not both. \`pulse.rhythm\`: \`regular\` | \`skips\` | \`irregular\` (a clearly irregular rhythm is the level-B red flag \`RF_B_IRREGULAR_PULSE\`).`, "");
  out.push(...table(["id", "group", "中文", "English", "脈象"], kb.pulse.pulses.map((x) => [`\`${x.id}\``, x.group, x.name["zh-Hant"], x.name.en, x.feature])), "");
  return `${out.join("\n")}\n`;
}
